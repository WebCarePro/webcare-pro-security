<?php
declare(strict_types=1);

namespace WebCareProScanner\Tests\Unit;

use PHPUnit\Framework\TestCase;
use WebCareProScanner\Contracts\RequestContext;
use WebCareProScanner\Contracts\WafAction;
use WebCareProScanner\Firewall\Evaluators\AiAgentBehaviorEvaluator;
use WebCareProScanner\System\SettingsManager;

final class AiAgentBehaviorEvaluatorTest extends TestCase {

    private AiAgentBehaviorEvaluator $evaluator;
    private array $origServer = [];
    private array $origPost = [];

    protected function setUp(): void {
        parent::setUp();
        $this->origServer = $_SERVER;
        $this->origPost = $_POST;
        $this->evaluator = new AiAgentBehaviorEvaluator();
        SettingsManager::update_setting('waf_ai_challenge_stealth_agents', true);
        SettingsManager::update_setting('waf_ai_allow_search_citations', true);
        $_SERVER = ['HTTP_HOST' => 'example.com'];
    }

    protected function tearDown(): void {
        $_SERVER = $this->origServer;
        $_POST = $this->origPost;
        parent::tearDown();
    }

    public function test_flags_missing_sec_fetch_on_desktop_https(): void {
        $_SERVER['HTTPS'] = 'on';
        $_SERVER['REQUEST_METHOD'] = 'POST';
        // HMAC-signed Sub-250ms velocity token generated by evaluator
        $_POST['webcare_render_ts'] = AiAgentBehaviorEvaluator::generate_render_timestamp();

        $ctx = new RequestContext(
            ip: '198.51.100.25',
            method: 'POST',
            uri: '/wp-comments-post.php',
            userAgent: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
        );

        $verdict = $this->evaluator->evaluate_runtime_request($ctx);
        $this->assertNotNull($verdict);
        $this->assertSame(WafAction::Challenge, $verdict->action);
        $this->assertSame('WAF-AI-AGENT-STEPUP', $verdict->ruleId);
    }

    public function test_permits_verified_search_citation_bot(): void {
        $ctx = new RequestContext(
            ip: '198.51.100.50',
            method: 'GET',
            uri: '/sample-post/',
            userAgent: 'Mozilla/5.0 (compatible; PerplexityBot/1.0; +https://perplexity.ai/perplexitybot)'
        );

        $verdict = $this->evaluator->evaluate_runtime_request($ctx);
        $this->assertNull($verdict);
    }

    public function test_canonical_same_site_referer_with_browser_ua_softens_stepup_on_human_post(): void {
        $_SERVER['HTTPS'] = 'on';
        $_SERVER['REQUEST_METHOD'] = 'POST';

        $ctx = new RequestContext(
            ip: '198.51.100.60',
            method: 'POST',
            uri: '/contact-us-email/',
            userAgent: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0.0.0 Safari/537.36 OPR/125.0.0.0',
            headers: [
                'host' => 'example.com',
                'referer' => 'https://example.com/contact-us-email/',
                'accept-language' => 'en-US,en;q=0.9',
            ],
            server: [
                'HTTPS' => 'on',
                'HTTP_HOST' => 'example.com',
                'HTTP_REFERER' => 'https://example.com/contact-us-email/',
            ]
        );

        $verdict = $this->evaluator->evaluate_runtime_request($ctx);
        $this->assertNull($verdict);
    }

    public function test_spoofed_host_matching_referer_mismatching_canonical_origin_triggers_stepup(): void {
        $_SERVER['HTTPS'] = 'on';
        $_SERVER['REQUEST_METHOD'] = 'POST';

        $ctx = new RequestContext(
            ip: '198.51.100.61',
            method: 'POST',
            uri: '/contact-us-email/',
            userAgent: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0.0.0 Safari/537.36',
            headers: [
                'host' => 'evil-spoof.test',
                'referer' => 'https://evil-spoof.test/contact-us-email/',
                'accept-language' => 'en-US,en;q=0.9',
            ],
            server: [
                'HTTPS' => 'on',
                'HTTP_HOST' => 'evil-spoof.test',
                'HTTP_REFERER' => 'https://evil-spoof.test/contact-us-email/',
            ]
        );

        $verdict = $this->evaluator->evaluate_runtime_request($ctx);
        $this->assertNotNull($verdict);
        $this->assertSame(WafAction::Challenge, $verdict->action);
        $this->assertSame('WAF-AI-AGENT-STEPUP', $verdict->ruleId);
    }
}
